import java.util.*;
public class Datatype{
    public static void main(String[] args){
        int a=50000;
        short s=2000;
        long l=10000000L;
        float f = 12.5f;
        double d = 123.456;
        char c = 'A';
        boolean flag = true;
       System.out.println(a);
       System.out.println(s);
       System.out.println(l);
       System.out.println(f);
       System.out.println(d);
       System.out.println(c);
       System.out.println(flag);
    }

}
